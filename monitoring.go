package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"vllm-manager/api"
)

const defaultMonitoringTargetsFile = "monitoring/runtime/vllm-targets.yml"

type monitoringOptions struct {
	Enabled     bool
	TargetsFile string
}

func syncMonitoringTargets(opts monitoringOptions) {
	if !opts.Enabled {
		return
	}
	if err := writeMonitoringTargets(opts); err != nil {
		log.Printf("[MONITORING] warning: failed to sync Prometheus targets: %v", err)
	}
}

func writeMonitoringTargets(opts monitoringOptions) error {
	path := strings.TrimSpace(opts.TargetsFile)
	if path == "" {
		path = defaultMonitoringTargetsFile
	}
	models, err := api.GetActiveModels(getSettings().VLLMAPIKey)
	if err != nil {
		return err
	}
	targets := make([]api.ActiveModel, 0, len(models))
	for _, model := range models {
		if model.State != "running" || strings.TrimSpace(model.MetricsTarget) == "" {
			continue
		}
		targets = append(targets, model)
	}
	sort.Slice(targets, func(i, j int) bool {
		if targets[i].Model == targets[j].Model {
			return targets[i].Port < targets[j].Port
		}
		return targets[i].Model < targets[j].Model
	})

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Generated by vllm-manager. Do not edit by hand.\n")
	for _, model := range targets {
		b.WriteString("- targets:\n")
		b.WriteString("    - ")
		b.WriteString(yamlQuote(model.MetricsTarget))
		b.WriteString("\n")
		b.WriteString("  labels:\n")
		writeYAMLLabel(&b, "job", "vllm")
		writeYAMLLabel(&b, "model", model.Model)
		writeYAMLLabel(&b, "port", model.Port)
		writeYAMLLabel(&b, "bind_ip", model.BindIP)
		writeYAMLLabel(&b, "container_name", model.ContainerName)
		writeYAMLLabel(&b, "container_id", shortContainerID(model.ContainerID))
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

func writeYAMLLabel(b *strings.Builder, key string, value string) {
	b.WriteString("    ")
	b.WriteString(key)
	b.WriteString(": ")
	b.WriteString(yamlQuote(value))
	b.WriteString("\n")
}

func yamlQuote(value string) string {
	return strconv.Quote(value)
}

func shortContainerID(value string) string {
	value = strings.TrimSpace(value)
	if len(value) <= 12 {
		return value
	}
	return value[:12]
}

func monitoringStartMessage(opts monitoringOptions) string {
	if !opts.Enabled {
		return ""
	}
	return fmt.Sprintf("Prometheus target sync enabled: %s", opts.TargetsFile)
}
